-- =============================================================================
-- SURTIFY · 12_comprobantes_pago.sql  —  Foto del comprobante de pago como soporte
--   * Bucket privado 'comprobantes' (solo imágenes, máx. 3 MB)
--   * Tabla comprobantes_pago: vincula la foto con una factura o con un abono de fiado
--   * adjuntar_comprobante(): valida sede/comercio y que la ruta sea de su comercio
--   * Evidencia inmutable: sin UPDATE ni DELETE para usuarios
--   * Lectura de la foto solo si el usuario puede ver la factura/abono asociado
-- =============================================================================

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('comprobantes', 'comprobantes', false, 3145728, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public = false, file_size_limit = 3145728,
  allowed_mime_types = array['image/jpeg','image/png','image/webp'];

create table if not exists comprobantes_pago (
  id_comprobante integer generated by default as identity primary key,
  id_comercio    integer not null references comercios(id_comercio) on delete cascade,
  id_sucursal    integer references sucursales(id_sucursal),
  id_empleado    integer references empleados(id_empleado) on delete set null,
  id_factura     integer references facturas(id_factura) on delete restrict,
  id_movimiento  integer references cartera_movimientos(id_movimiento) on delete restrict,
  ruta           text not null unique,
  creado         timestamptz not null default now(),
  check ((id_factura is null) <> (id_movimiento is null))
);
create index if not exists idx_comprob_factura on comprobantes_pago(id_factura);
create index if not exists idx_comprob_mov on comprobantes_pago(id_movimiento);
create index if not exists idx_comprob_comercio on comprobantes_pago(id_comercio);
create index if not exists idx_comprob_sucursal on comprobantes_pago(id_sucursal);
create index if not exists idx_comprob_empleado on comprobantes_pago(id_empleado);

alter table comprobantes_pago enable row level security;
revoke all on comprobantes_pago from anon, authenticated;
grant select on comprobantes_pago to authenticated;
drop policy if exists "comprob_select" on comprobantes_pago;
create policy "comprob_select" on comprobantes_pago for select to authenticated
  using (id_comercio = (select app.mi_comercio())
         and (id_sucursal is null or app.puede_ver_sucursal(id_sucursal)));

create or replace function public.adjuntar_comprobante(p_id_factura integer, p_id_movimiento integer, p_ruta text)
returns integer language plpgsql security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_suc integer; v_id integer;
begin
  if v_com is null then raise exception 'No autenticado'; end if;
  if (p_id_factura is null) = (p_id_movimiento is null) then
    raise exception 'Indique la factura o el abono';
  end if;
  if p_ruta is null or split_part(p_ruta, '/', 1) <> v_com::text or p_ruta !~ '^[0-9]+/[A-Za-z0-9._-]+$' then
    raise exception 'Ruta de comprobante no válida';
  end if;
  if not exists (select 1 from storage.objects o where o.bucket_id = 'comprobantes' and o.name = p_ruta) then
    raise exception 'La imagen no se subió';
  end if;
  if p_id_factura is not null then
    select p.id_sucursal into v_suc from facturas f join pedidos p on p.id_pedido = f.id_pedido
     where f.id_factura = p_id_factura;
    if v_suc is null or not app.puede_ver_sucursal(v_suc) then raise exception 'Factura no encontrada'; end if;
  else
    select m.id_sucursal into v_suc from cartera_movimientos m
     where m.id_movimiento = p_id_movimiento and m.id_comercio = v_com and m.tipo = 'Abono';
    if not found then raise exception 'Abono no encontrado'; end if;
    if v_suc is not null and not app.puede_ver_sucursal(v_suc) then raise exception 'Abono no encontrado'; end if;
  end if;
  insert into comprobantes_pago(id_comercio, id_sucursal, id_empleado, id_factura, id_movimiento, ruta)
  values (v_com, v_suc, app.mi_empleado(), p_id_factura, p_id_movimiento, p_ruta)
  returning id_comprobante into v_id;
  return v_id;
end $$;
revoke all on function public.adjuntar_comprobante(integer,integer,text) from public, anon;
grant execute on function public.adjuntar_comprobante(integer,integer,text) to authenticated;

-- Políticas de Storage: subir solo a la carpeta del propio comercio; leer solo si hay un comprobante visible
drop policy if exists "comprob_subir" on storage.objects;
create policy "comprob_subir" on storage.objects for insert to authenticated
  with check (bucket_id = 'comprobantes' and (storage.foldername(name))[1] = (select app.mi_comercio())::text);
drop policy if exists "comprob_leer" on storage.objects;
create policy "comprob_leer" on storage.objects for select to authenticated
  using (bucket_id = 'comprobantes'
         and exists (select 1 from public.comprobantes_pago c where c.ruta = storage.objects.name));

-- registrar_abono ahora devuelve id_movimiento (para poder adjuntar el comprobante)
create or replace function public.registrar_abono(p_id_cliente integer, p_monto numeric, p_metodo_pago text, p_nota text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_emp integer := app.mi_empleado(); v_suc integer := app.mi_sucursal(); v_com integer := app.mi_comercio();
  v_ses integer; v_saldo numeric(12,2); v_cli record; v_mov integer;
begin
  if v_emp is null then raise exception 'Tu usuario no está vinculado a un empleado activo' using errcode = '42501'; end if;
  select id_sesion into v_ses from sesiones_caja where id_empleado = v_emp and estado_caja = 'Abierta' limit 1;
  if v_ses is null then raise exception 'Abre tu caja antes de recibir un abono'; end if;
  if p_metodo_pago not in ('Efectivo','Nequi','Daviplata','Bre-B','Tarjeta') then raise exception 'Método de pago no válido: %', p_metodo_pago; end if;
  if p_monto is null or p_monto <= 0 then raise exception 'El abono debe ser mayor que cero'; end if;
  select id_cliente, nombre, telefono into v_cli from clientes where id_cliente = p_id_cliente and id_comercio = v_com for update;
  if not found then raise exception 'Cliente no válido'; end if;
  select coalesce(sum(case when tipo = 'Cargo' then monto else -monto end), 0) into v_saldo from cartera_movimientos where id_cliente = p_id_cliente;
  if p_monto > v_saldo then raise exception 'El abono ($%) supera la deuda del cliente ($%)', p_monto, v_saldo; end if;

  insert into cartera_movimientos (id_comercio, id_cliente, id_sucursal, id_empleado, id_sesion, tipo, monto, metodo_pago, nota)
  values (v_com, p_id_cliente, v_suc, v_emp, v_ses, 'Abono', p_monto, p_metodo_pago, nullif(btrim(coalesce(p_nota, '')), ''))
  returning id_movimiento into v_mov;
  if p_metodo_pago = 'Efectivo' then   -- el dinero entra al cajón
    update sesiones_caja set monto_cierre_esperado = coalesce(monto_cierre_esperado, monto_apertura) + p_monto where id_sesion = v_ses;
  end if;
  return jsonb_build_object('id_movimiento', v_mov, 'id_cliente', p_id_cliente, 'nombre', v_cli.nombre, 'telefono', v_cli.telefono,
    'abono', p_monto, 'saldo_anterior', v_saldo, 'saldo_nuevo', v_saldo - p_monto, 'metodo_pago', p_metodo_pago, 'caja', app.resumen_sesion(v_ses));
end $$;

-- Listado de facturas: cuántos comprobantes tiene cada una (columna añadida AL FINAL)
create or replace view v_facturas_recientes with (security_invoker = true) as
select f.id_factura, f.numero_factura, f.fecha_emision, f.total_facturado, f.metodo_pago,
       s.nombre_sucursal as sucursal, e.nombre as cajero,
       coalesce((select sum(nc.total_reversado) from notas_credito nc where nc.id_factura = f.id_factura), 0) as devuelto,
       p.id_sucursal, p.id_empleado, c.nombre as cliente,
       coalesce((select sum(df.cantidad) from detalles_factura df where df.id_factura = f.id_factura), 0)::int as unidades,
       (select count(*) from comprobantes_pago cp where cp.id_factura = f.id_factura)::int as n_comprobantes
  from facturas f
  join pedidos p on p.id_pedido = f.id_pedido
  join sucursales s on s.id_sucursal = p.id_sucursal
  left join empleados e on e.id_empleado = p.id_empleado
  left join clientes c on c.id_cliente = p.id_cliente;
grant select on v_facturas_recientes to authenticated;
