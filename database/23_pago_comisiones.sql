-- =============================================================================
-- SURTIFY · 23_pago_comisiones.sql
--   Marcar comisiones como pagadas (cierre de quincena / semana / mes).
--   * comisiones_pagos: cada pago hecho a una persona (monto, hasta qué fecha, nota, quién lo registró).
--   * Cada línea de venta queda ligada al pago que la cubrió (detalles_pedido.id_pago_comision).
--   * Devoluciones posteriores a un pago: la parte de comisión ya pagada que se devuelve queda como
--     ajuste en contra y se descuenta en el siguiente pago (no se reescribe el pago anterior).
--   * Funciones: comisiones_pendientes(), comisiones_pagar(persona, hasta, nota), comisiones_pagos_listar().
--     Pagar es solo del administrador; cada persona ve lo suyo.
--   Ejecutar después de 22_servicios_y_comisiones.sql.
-- =============================================================================

create table if not exists comisiones_pagos (
  id_pago      bigint generated by default as identity primary key,
  id_comercio  integer not null references comercios(id_comercio) on delete cascade,
  id_empleado  integer not null references empleados(id_empleado) on delete cascade,
  hasta        date not null,
  monto        numeric(12,2) not null check (monto > 0),
  lineas       integer not null check (lineas > 0),
  nota         text check (nota is null or length(nota) <= 200),
  id_actor     integer references empleados(id_empleado) on delete set null,
  creado       timestamptz not null default now()
);
create index if not exists comisiones_pagos_emp_idx on comisiones_pagos (id_comercio, id_empleado, creado desc);
alter table comisiones_pagos enable row level security;
revoke all on comisiones_pagos from anon, authenticated;   -- solo se accede por las funciones de abajo

alter table detalles_pedido add column if not exists id_pago_comision bigint references comisiones_pagos(id_pago) on delete restrict;
alter table detalles_pedido add column if not exists comision_dev_pagada numeric(12,2) not null default 0;
comment on column detalles_pedido.id_pago_comision is 'Pago de comisión que cubrió esta línea (NULL = pendiente)';
comment on column detalles_pedido.comision_dev_pagada is 'Parte devuelta de la comisión que ya se tuvo en cuenta al pagar';

-- ---------- Líneas con comisión por pagar (interno) ----------
-- pendiente: línea sin pagar = comisión menos lo devuelto; línea ya pagada = ajuste negativo por devoluciones posteriores.
create or replace function app.comision_lineas(p_com integer, p_emp integer, p_hasta date)
returns table (id_detalle integer, id_empleado integer, fecha timestamptz, comision numeric, comision_dev numeric, pagada boolean, pendiente numeric)
language sql stable security definer set search_path = public as $$
  with base as (
    select d.id_detalle, d.id_empleado_servicio as id_empleado, f.fecha_emision as fecha, d.cantidad, d.comision_valor,
           d.id_pago_comision, d.comision_dev_pagada,
           sum(d.cantidad) over (partition by f.id_factura, d.id_producto) as q_total,
           coalesce((select sum(dn.cantidad_devuelta) from detalles_nota_credito dn
                       join notas_credito nc on nc.id_nota_credito = dn.id_nota_credito
                      where nc.id_factura = f.id_factura and dn.id_producto = d.id_producto), 0) as q_dev
      from detalles_pedido d
      join pedidos pe on pe.id_pedido = d.id_pedido
      join sucursales su on su.id_sucursal = pe.id_sucursal and su.id_comercio = p_com
      join facturas f on f.id_pedido = pe.id_pedido
     where d.id_empleado_servicio is not null and d.comision_valor > 0
       and (p_emp is null or d.id_empleado_servicio = p_emp)
  ), calc as (
    select b.*, round(b.comision_valor * least((b.q_dev * b.cantidad::numeric / nullif(b.q_total, 0)) / b.cantidad, 1), 2) as dev
      from base b
  )
  select c.id_detalle, c.id_empleado, c.fecha, c.comision_valor, c.dev, c.id_pago_comision is not null,
         case when c.id_pago_comision is null then c.comision_valor - c.dev else -(c.dev - c.comision_dev_pagada) end
    from calc c
   where (c.id_pago_comision is null and (c.fecha at time zone 'America/Bogota')::date <= p_hasta and c.comision_valor - c.dev <> 0)
      or (c.id_pago_comision is not null and c.dev <> c.comision_dev_pagada)
$$;
revoke all on function app.comision_lineas(integer, integer, date) from public, anon, authenticated;

-- ---------- Pendiente por persona ----------
create or replace function public.comisiones_pendientes()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_adm boolean := app.es_admin(); v_yo integer := app.mi_empleado();
  v_hoy date := (now() at time zone 'America/Bogota')::date;
begin
  if v_yo is null then raise exception 'Tu usuario no está vinculado a un empleado activo' using errcode = '42501'; end if;
  if not v_adm and not app.tiene_permiso('vender') then raise exception 'Tu rol no tiene permiso para esto' using errcode = '42501'; end if;
  return jsonb_build_object('hasta', v_hoy, 'personas', coalesce((
    select jsonb_agg(jsonb_build_object('id_empleado', x.id_empleado, 'nombre', e.nombre, 'pendiente', x.total,
                     'lineas', x.n, 'desde', (x.primera at time zone 'America/Bogota')::date) order by x.total desc, e.nombre)
      from (select l.id_empleado, sum(l.pendiente) as total, count(*)::int as n, min(l.fecha) as primera
              from app.comision_lineas(v_com, case when v_adm then null else v_yo end, v_hoy) l
             group by l.id_empleado having sum(l.pendiente) <> 0) x
      join empleados e on e.id_empleado = x.id_empleado), '[]'::jsonb));
end $$;

-- ---------- Marcar como pagado ----------
create or replace function public.comisiones_pagar(p_id_empleado integer, p_hasta date default null, p_nota text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_hoy date := (now() at time zone 'America/Bogota')::date;
  v_hasta date := coalesce(p_hasta, v_hoy); v_nota text := nullif(btrim(coalesce(p_nota, '')), '');
  v_monto numeric(12,2); v_n integer; v_id bigint; v_nombre text;
begin
  if not app.es_admin() then raise exception 'Solo el administrador puede registrar pagos de comisiones' using errcode = '42501'; end if;
  if v_hasta > v_hoy then raise exception 'La fecha no puede ser futura'; end if;
  if v_nota is not null and length(v_nota) > 200 then raise exception 'La nota es demasiado larga'; end if;
  select e.nombre into v_nombre from empleados e join sucursales s on s.id_sucursal = e.id_sucursal
   where e.id_empleado = p_id_empleado and s.id_comercio = v_com for update of e;   -- un pago a la vez por persona
  if not found then raise exception 'Persona no encontrada'; end if;

  select coalesce(sum(pendiente), 0), count(*) into v_monto, v_n from app.comision_lineas(v_com, p_id_empleado, v_hasta);
  if v_monto <= 0 then raise exception 'No hay comisión por pagar a % hasta esa fecha', v_nombre; end if;

  insert into comisiones_pagos (id_comercio, id_empleado, hasta, monto, lineas, nota, id_actor)
  values (v_com, p_id_empleado, v_hasta, v_monto, v_n, v_nota, app.mi_empleado()) returning id_pago into v_id;

  update detalles_pedido d
     set id_pago_comision = coalesce(d.id_pago_comision, v_id), comision_dev_pagada = l.comision_dev
    from app.comision_lineas(v_com, p_id_empleado, v_hasta) l
   where d.id_detalle = l.id_detalle;

  perform app.equipo_log(v_com, app.mi_empleado(), p_id_empleado, 'comision_pago',
                         'Pago de comisiones $' || to_char(v_monto, 'FM999G999G999') || ' hasta ' || to_char(v_hasta, 'DD/MM'));
  return jsonb_build_object('id_pago', v_id, 'monto', v_monto, 'lineas', v_n, 'hasta', v_hasta);
end $$;

-- ---------- Historial de pagos ----------
create or replace function public.comisiones_pagos_listar(p_id_empleado integer default null, p_limite integer default 20)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_adm boolean := app.es_admin(); v_yo integer := app.mi_empleado();
begin
  if v_yo is null then raise exception 'Tu usuario no está vinculado a un empleado activo' using errcode = '42501'; end if;
  if not v_adm and not app.tiene_permiso('vender') then raise exception 'Tu rol no tiene permiso para esto' using errcode = '42501'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object('id_pago', q.id_pago, 'persona', q.persona, 'monto', q.monto, 'lineas', q.lineas,
                    'hasta', q.hasta, 'nota', q.nota, 'registro', q.registro, 'creado', q.creado) order by q.creado desc)
      from (select p.id_pago, e.nombre as persona, p.monto, p.lineas, p.hasta, p.nota, a.nombre as registro, p.creado
              from comisiones_pagos p join empleados e on e.id_empleado = p.id_empleado left join empleados a on a.id_empleado = p.id_actor
             where p.id_comercio = v_com
               and p.id_empleado = case when v_adm then coalesce(p_id_empleado, p.id_empleado) else v_yo end
             order by p.creado desc limit least(greatest(coalesce(p_limite, 20), 1), 100)) q), '[]'::jsonb);
end $$;

-- ---------- El reporte marca qué líneas ya se pagaron ----------
do $$
declare v_def text; v_new text;
begin
  v_def := pg_get_functiondef('public.reporte_comisiones(date,date,integer)'::regprocedure);
  v_new := replace(v_def, 'd.id_empleado_servicio as id_empleado,', 'd.id_empleado_servicio as id_empleado, d.id_pago_comision,');
  v_new := replace(v_new, '''comision_devuelta'', f2.comision_dev)', '''comision_devuelta'', f2.comision_dev, ''pagada'', f2.id_pago_comision is not null)');
  if v_new = v_def or position('''pagada''' in v_new) = 0 or position('d.id_pago_comision' in v_new) = 0 then
    raise exception 'Sin cambios en reporte_comisiones'; end if;
  execute v_new;
end $$;

