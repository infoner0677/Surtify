create or replace function public.registrar_abono(p_id_cliente integer, p_monto numeric, p_metodo_pago text, p_nota text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_emp integer := app.mi_empleado(); v_suc integer := app.mi_sucursal(); v_com integer := app.mi_comercio();
  v_ses integer; v_saldo numeric(12,2); v_cli record;
begin
  if v_emp is null then raise exception 'Tu usuario no está vinculado a un empleado activo' using errcode = '42501'; end if;
  select id_sesion into v_ses from sesiones_caja where id_empleado = v_emp and estado_caja = 'Abierta' limit 1;
  if v_ses is null then raise exception 'Abre tu caja antes de recibir un abono'; end if;
  if p_metodo_pago not in ('Efectivo','Nequi','Daviplata','Bre-B','Tarjeta') then raise exception 'Método de pago no válido: %', p_metodo_pago; end if;
  if p_monto is null or p_monto <= 0 then raise exception 'El abono debe ser mayor que cero'; end if;
  select id_cliente, nombre, telefono into v_cli from clientes where id_cliente = p_id_cliente and id_comercio = v_com for update;
  if not found then raise exception 'Cliente no válido'; end if;
  select coalesce(sum(case when tipo = 'Cargo' then monto else -monto end), 0) into v_saldo from cartera_movimientos where id_cliente = p_id_cliente;
  if p_monto > v_saldo then raise exception 'El abono ($%) supera la deuda del cliente ($%)', p_monto, v_saldo; end if;

  insert into cartera_movimientos (id_comercio, id_cliente, id_sucursal, id_empleado, id_sesion, tipo, monto, metodo_pago, nota)
  values (v_com, p_id_cliente, v_suc, v_emp, v_ses, 'Abono', p_monto, p_metodo_pago, nullif(btrim(coalesce(p_nota, '')), ''));
  if p_metodo_pago = 'Efectivo' then   -- el dinero entra al cajón
    update sesiones_caja set monto_cierre_esperado = coalesce(monto_cierre_esperado, monto_apertura) + p_monto where id_sesion = v_ses;
  end if;
  return jsonb_build_object('id_cliente', p_id_cliente, 'nombre', v_cli.nombre, 'telefono', v_cli.telefono,
    'abono', p_monto, 'saldo_anterior', v_saldo, 'saldo_nuevo', v_saldo - p_monto, 'metodo_pago', p_metodo_pago, 'caja', app.resumen_sesion(v_ses));
end $$;

