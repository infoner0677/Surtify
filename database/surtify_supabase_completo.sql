-- =============================================================================
-- SURTIFY · Migración MySQL 8 -> PostgreSQL (Supabase)
-- 01_esquema.sql · Estructura de tablas (DDL)
--
-- Se conservan los nombres de tablas y columnas del informe ACA para que la
-- documentación siga siendo válida. Cambios respecto a MySQL (todos intencionales):
--   * AUTO_INCREMENT -> IDENTITY · TIMESTAMP -> timestamptz · ENUM -> CHECK
--   * DECIMAL(10,2) -> numeric(12,2) (más margen para montos en COP)
--   * empleados.contrasena_hash ELIMINADA: la autenticación la hace Supabase Auth
--     (bcrypt + salt); se enlaza con empleados.auth_user_id.
--   * productos.id_comercio AÑADIDA (aislamiento multi-inquilino directo).
--   * roles.es_administrador, productos.iva_porcentaje, productos.activo,
--     empleados.activo, comercios.prefijo/consecutivo_factura y
--     facturas.monto_recibido/monto_cambio AÑADIDAS (necesarias para el POS).
--   * Restricciones nuevas: stock >= 0, cantidades > 0, una sola caja abierta
--     por empleado, identificación única POR COMERCIO (no global).
-- =============================================================================

-- ---------- Núcleo del inquilino (SaaS) ----------
create table comercios (
  id_comercio          integer generated by default as identity primary key,
  nombre_comercial     varchar(150) not null,
  razon_social         varchar(150),
  nit_rut              varchar(50) unique,
  fecha_registro       timestamptz not null default now(),
  prefijo_factura      varchar(10) not null default 'FAC',
  consecutivo_factura  integer not null default 0 check (consecutivo_factura >= 0)
);

create table modulos_suscripcion (
  id_modulo       integer generated by default as identity primary key,
  nombre_modulo   varchar(100) not null,
  descripcion     text,
  precio_mensual  numeric(12,2) not null check (precio_mensual >= 0)
);

create table suscripciones_comercio (
  id_suscripcion     integer generated by default as identity primary key,
  id_comercio        integer references comercios(id_comercio) on delete cascade,
  id_modulo          integer references modulos_suscripcion(id_modulo),
  fecha_activacion   date not null,
  fecha_vencimiento  date not null,
  ciclo_facturacion  varchar(20) default 'Mensual' check (ciclo_facturacion in ('Mensual','Anual')),
  estado             varchar(20) default 'Activo'  check (estado in ('Activo','Inactivo','Demo')),
  metodo_pago        varchar(50) default 'Transferencia'
);

create table sucursales (
  id_sucursal      integer generated by default as identity primary key,
  id_comercio      integer references comercios(id_comercio) on delete cascade,
  nombre_sucursal  varchar(100) not null,
  direccion        varchar(255) not null,
  telefono         varchar(20)
);

-- ---------- Estructura interna ----------
create table roles (
  id_role           integer generated by default as identity primary key,
  id_comercio       integer references comercios(id_comercio) on delete cascade,
  nombre_rol        varchar(100) not null,
  descripcion       text,
  es_administrador  boolean not null default false
);

create table empleados (
  id_empleado            integer generated by default as identity primary key,
  id_sucursal            integer references sucursales(id_sucursal) on delete cascade,
  id_role                integer references roles(id_role) on delete set null,
  numero_identificacion  varchar(20) unique,
  tipo_documento         varchar(5) default 'CC',
  nombre                 varchar(100) not null,
  salario                numeric(12,2) not null check (salario >= 0),
  email                  varchar(150) not null unique,
  auth_user_id           uuid unique references auth.users(id) on delete set null,
  activo                 boolean not null default true
);

create table permisos_rol_modulo (
  id_permiso        integer generated by default as identity primary key,
  id_role           integer references roles(id_role) on delete cascade,
  id_modulo         integer references modulos_suscripcion(id_modulo) on delete cascade,
  puede_crear       boolean default false,
  puede_leer        boolean default true,
  puede_actualizar  boolean default false,
  puede_eliminar    boolean default false
);

create table proveedores (
  id_proveedor      integer generated by default as identity primary key,
  id_comercio       integer references comercios(id_comercio) on delete cascade,
  nombre_proveedor  varchar(150) not null,
  contacto          varchar(100),
  telefono          varchar(20),
  email             varchar(150)
);

-- ---------- Inventario ----------
create table categorias (
  id_categoria  integer generated by default as identity primary key,
  id_comercio   integer references comercios(id_comercio) on delete cascade,
  nombre        varchar(100) not null,
  descripcion   text
);

create table productos (
  id_producto     integer generated by default as identity primary key,
  id_comercio     integer not null references comercios(id_comercio) on delete cascade,
  id_categoria    integer references categorias(id_categoria) on delete set null,
  nombre          varchar(150) not null,
  descripcion     text,
  precio_venta    numeric(12,2) not null check (precio_venta >= 0),   -- IVA incluido
  iva_porcentaje  numeric(5,2) not null default 0 check (iva_porcentaje between 0 and 100),
  codigo_barras   varchar(100),
  activo          boolean not null default true
);

create table inventarios_sucursal (
  id_inventario  integer generated by default as identity primary key,
  id_sucursal    integer references sucursales(id_sucursal) on delete cascade,
  id_producto    integer references productos(id_producto) on delete cascade,
  stock          integer not null default 0 check (stock >= 0),
  stock_minimo   integer default 5 check (stock_minimo >= 0),
  unique (id_sucursal, id_producto)
);

-- ---------- Operaciones ----------
create table clientes (
  id_cliente             integer generated by default as identity primary key,
  id_comercio            integer references comercios(id_comercio) on delete cascade,
  numero_identificacion  varchar(20),
  tipo_documento         varchar(5) default 'CC',
  nombre                 varchar(100) not null,
  telefono               varchar(20),
  email                  varchar(150),
  tipo_persona           varchar(10) default 'Natural' check (tipo_persona in ('Natural','Jurídica')),
  regimen_tributario     varchar(30) default 'No Responsable de IVA'
    check (regimen_tributario in ('Régimen Ordinario','Simple de Sanciones','Gran Contribuyente','No Responsable de IVA')),
  puntos_fidelidad       integer default 0 check (puntos_fidelidad >= 0),
  unique (id_comercio, numero_identificacion)
);

create table pedidos (
  id_pedido     integer generated by default as identity primary key,
  id_sucursal   integer references sucursales(id_sucursal),
  id_cliente    integer references clientes(id_cliente) on delete set null,
  id_empleado   integer references empleados(id_empleado) on delete set null,
  fecha_pedido  timestamptz not null default now(),
  total         numeric(12,2) default 0 check (total >= 0),
  estado        varchar(50) default 'En Preparacion'
    check (estado in ('En Preparacion','Pendiente','Completado','Cancelado')),
  canal_venta   varchar(30) default 'Mostrador'
    check (canal_venta in ('Mostrador','POS','E-commerce'))
);

create table detalles_pedido (
  id_detalle       integer generated by default as identity primary key,
  id_pedido        integer references pedidos(id_pedido) on delete cascade,
  id_producto      integer references productos(id_producto),
  cantidad         integer not null check (cantidad > 0),
  precio_unitario  numeric(12,2) not null check (precio_unitario >= 0)
);

create table facturas (
  id_factura       integer generated by default as identity primary key,
  id_pedido        integer unique references pedidos(id_pedido) on delete restrict,
  numero_factura   varchar(50) not null,
  fecha_emision    timestamptz not null default now(),
  subtotal         numeric(12,2) not null,
  impuestos        numeric(12,2) default 0,
  total_facturado  numeric(12,2) not null check (total_facturado >= 0),
  metodo_pago      varchar(50) not null,
  monto_recibido   numeric(12,2),
  monto_cambio     numeric(12,2),
  estado_dian      varchar(30) default 'Pendiente Envio'
);

create table detalles_factura (
  id_detalle_factura         integer generated by default as identity primary key,
  id_factura                 integer references facturas(id_factura) on delete cascade,
  id_producto                integer references productos(id_producto) on delete set null,
  nombre_producto_historico  varchar(150) not null,
  cantidad                   integer not null check (cantidad > 0),
  precio_unitario            numeric(12,2) not null,
  iva_aplicado               numeric(5,2) default 0,
  total_linea                numeric(12,2) not null
);

create table notas_credito (
  id_nota_credito  integer generated by default as identity primary key,
  id_factura       integer not null references facturas(id_factura) on delete restrict,
  numero_nota      varchar(50) not null,
  fecha_emision    timestamptz not null default now(),
  motivo_dian      varchar(255) not null,
  total_reversado  numeric(12,2) not null check (total_reversado >= 0),
  estado_dian      varchar(30) default 'Pendiente Envio'
);

create table detalles_nota_credito (
  id_detalle_nota            integer generated by default as identity primary key,
  id_nota_credito            integer references notas_credito(id_nota_credito) on delete cascade,
  id_producto                integer references productos(id_producto) on delete set null,
  cantidad_devuelta          integer not null check (cantidad_devuelta > 0),
  precio_unitario_reversado  numeric(12,2) not null,
  total_linea_reversado      numeric(12,2) not null
);

-- ---------- Caja ----------
create table sesiones_caja (
  id_sesion               integer generated by default as identity primary key,
  id_sucursal             integer references sucursales(id_sucursal),
  id_empleado             integer references empleados(id_empleado),
  fecha_apertura          timestamptz not null default now(),
  fecha_cierre            timestamptz,
  monto_apertura          numeric(12,2) not null default 0 check (monto_apertura >= 0),
  monto_cierre_real       numeric(12,2),
  monto_cierre_esperado   numeric(12,2),   -- SOLO efectivo físico esperado en el cajón
  estado_caja             varchar(20) default 'Abierta' check (estado_caja in ('Abierta','Cerrada'))
);

create table movimientos_caja (
  id_movimiento     integer generated by default as identity primary key,
  id_sesion         integer references sesiones_caja(id_sesion) on delete cascade,
  tipo_movimiento   varchar(20) not null check (tipo_movimiento in ('Ingreso','Egreso')),
  metodo_pago       varchar(50) not null,
  monto_recibido    numeric(12,2) not null,
  monto_cambio      numeric(12,2) default 0,
  monto_neto        numeric(12,2) not null check (monto_neto >= 0),
  id_factura        integer references facturas(id_factura),
  id_nota_credito   integer references notas_credito(id_nota_credito),
  fecha_movimiento  timestamptz not null default now()
);

create table gastos_caja (
  id_gasto     integer generated by default as identity primary key,
  id_sesion    integer references sesiones_caja(id_sesion) on delete cascade,
  monto_gasto  numeric(12,2) not null check (monto_gasto > 0),
  concepto     varchar(100) not null,
  descripcion  text,
  fecha_gasto  timestamptz not null default now()
);

create table sistema_acerca_de (
  parametro  varchar(50) primary key,
  valor      text not null
);

