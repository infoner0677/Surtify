create or replace function public.adjuntar_comprobante(p_id_factura integer, p_id_movimiento integer, p_ruta text)
returns integer language plpgsql security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_suc integer; v_id integer;
begin
  if v_com is null then raise exception 'No autenticado'; end if;
  if (p_id_factura is null) = (p_id_movimiento is null) then
    raise exception 'Indique la factura o el abono';
  end if;
  if p_ruta is null or split_part(p_ruta, '/', 1) <> v_com::text or p_ruta !~ '^[0-9]+/[A-Za-z0-9._-]+$' then
    raise exception 'Ruta de comprobante no válida';
  end if;
  if not exists (select 1 from storage.objects o where o.bucket_id = 'comprobantes' and o.name = p_ruta) then
    raise exception 'La imagen no se subió';
  end if;
  if p_id_factura is not null then
    select p.id_sucursal into v_suc from facturas f join pedidos p on p.id_pedido = f.id_pedido
     where f.id_factura = p_id_factura;
    if v_suc is null or not app.puede_ver_sucursal(v_suc) then raise exception 'Factura no encontrada'; end if;
  else
    select m.id_sucursal into v_suc from cartera_movimientos m
     where m.id_movimiento = p_id_movimiento and m.id_comercio = v_com and m.tipo = 'Abono';
    if not found then raise exception 'Abono no encontrado'; end if;
    if v_suc is not null and not app.puede_ver_sucursal(v_suc) then raise exception 'Abono no encontrado'; end if;
  end if;
  insert into comprobantes_pago(id_comercio, id_sucursal, id_empleado, id_factura, id_movimiento, ruta)
  values (v_com, v_suc, app.mi_empleado(), p_id_factura, p_id_movimiento, p_ruta)
  returning id_comprobante into v_id;
  return v_id;
end $$;
