  if v_ced is not null and exists (select 1 from clientes where id_comercio = v_com and numero_identificacion = v_ced) then
    raise exception 'Ya existe un cliente con esa cédula';
  end if;
  insert into clientes (id_comercio, nombre, telefono, numero_identificacion, cupo_fiado)
  values (v_com, btrim(p_nombre), v_tel, v_ced, p_cupo) returning id_cliente into v_id;
  return jsonb_build_object('id_cliente', v_id, 'nombre', btrim(p_nombre), 'telefono', v_tel, 'cupo_fiado', p_cupo);
end $$;

