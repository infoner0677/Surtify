-- ---------- Agregar persona (solo la fila de empleado; el acceso lo crea la Edge Function) ----------
create or replace function public.equipo_crear(p_nombre text, p_email text, p_id_sucursal integer, p_id_role integer)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_email text := lower(btrim(coalesce(p_email, ''))); v_id integer;
begin
  if not app.es_admin() then raise exception 'Solo el administrador puede agregar personas' using errcode = '42501'; end if;
  if length(btrim(coalesce(p_nombre, ''))) < 2 or length(btrim(p_nombre)) > 100 then raise exception 'Escribe el nombre de la persona'; end if;
  if v_email !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' or length(v_email) > 150 then raise exception 'El correo no es válido'; end if;
  if not exists (select 1 from sucursales where id_sucursal = p_id_sucursal and id_comercio = v_com and not coalesce(autoservicio, false)) then
    raise exception 'Sede no válida'; end if;
  if not exists (select 1 from roles where id_role = p_id_role and id_comercio = v_com) then raise exception 'Rol no válido'; end if;
  if exists (select 1 from empleados where lower(email) = v_email) then raise exception 'Ese correo ya está en uso'; end if;
  insert into empleados (id_sucursal, id_role, nombre, salario, email, activo)
  values (p_id_sucursal, p_id_role, btrim(p_nombre), 0, v_email, true) returning id_empleado into v_id;
  perform app.equipo_log(v_com, app.mi_empleado(), v_id, 'agregado', btrim(p_nombre));
  return jsonb_build_object('id_empleado', v_id, 'email', v_email);
end $$;

-- Deshace una alta cuando falló la creación del acceso (solo si aún no tiene acceso ni historial)
create or replace function public.equipo_descartar(p_id_empleado integer)
returns void language plpgsql security definer set search_path = public as $$
declare v_com integer := app.mi_comercio();
begin
  if not app.es_admin() then raise exception 'Solo el administrador puede gestionar el equipo' using errcode = '42501'; end if;
  begin
    delete from empleados e using sucursales s
     where e.id_empleado = p_id_empleado and s.id_sucursal = e.id_sucursal and s.id_comercio = v_com and e.auth_user_id is null;
  exception when foreign_key_violation then null;
  end;
end $$;

-- ---------- Cambiar rol / sede / activo ----------
create or replace function public.equipo_actualizar(p_id_empleado integer, p_id_role integer default null, p_id_sucursal integer default null, p_activo boolean default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_com integer := app.mi_comercio(); v_yo integer := app.mi_empleado();
  t record; v_rol_admin boolean; v_nuevo_admin boolean; v_activo boolean; v_otros integer;
begin
  if not app.es_admin() then raise exception 'Solo el administrador puede gestionar el equipo' using errcode = '42501'; end if;
  select e.id_empleado, e.nombre, e.auth_user_id, e.activo, e.id_role, e.id_sucursal, coalesce(r.es_administrador, false) as es_admin
    into t from empleados e join sucursales s on s.id_sucursal = e.id_sucursal left join roles r on r.id_role = e.id_role
   where e.id_empleado = p_id_empleado and s.id_comercio = v_com;
  if not found then raise exception 'Persona no encontrada'; end if;
  if p_id_role is not null and not exists (select 1 from roles where id_role = p_id_role and id_comercio = v_com) then raise exception 'Rol no válido'; end if;
  if p_id_sucursal is not null and not exists (select 1 from sucursales where id_sucursal = p_id_sucursal and id_comercio = v_com and not coalesce(autoservicio, false)) then
    raise exception 'Sede no válida'; end if;

  v_activo := coalesce(p_activo, t.activo);
  select coalesce(es_administrador, false) into v_nuevo_admin from roles where id_role = coalesce(p_id_role, t.id_role);
  v_nuevo_admin := coalesce(v_nuevo_admin, false);

  if t.id_empleado = v_yo and (not v_activo or (t.es_admin and not v_nuevo_admin)) then
    raise exception 'No puedes desactivarte ni quitarte el rol de administrador a ti mismo'; end if;
  if t.es_admin and t.activo and (not v_activo or not v_nuevo_admin) then
    select count(*) into v_otros from empleados e join sucursales s on s.id_sucursal = e.id_sucursal join roles r on r.id_role = e.id_role
     where s.id_comercio = v_com and e.activo and r.es_administrador and e.id_empleado <> t.id_empleado;
    if v_otros = 0 then raise exception 'Debe quedar al menos un administrador activo'; end if;
  end if;

  update empleados set id_role = coalesce(p_id_role, id_role), id_sucursal = coalesce(p_id_sucursal, id_sucursal), activo = v_activo
   where id_empleado = t.id_empleado;
  if v_activo <> t.activo then perform app.equipo_log(v_com, v_yo, t.id_empleado, case when v_activo then 'reactivado' else 'desactivado' end, t.nombre); end if;
  if p_id_role is not null and p_id_role is distinct from t.id_role then
    perform app.equipo_log(v_com, v_yo, t.id_empleado, 'rol', (select nombre_rol from roles where id_role = p_id_role)); end if;
  if p_id_sucursal is not null and p_id_sucursal is distinct from t.id_sucursal then
    perform app.equipo_log(v_com, v_yo, t.id_empleado, 'sede', (select nombre_sucursal from sucursales where id_sucursal = p_id_sucursal)); end if;
  return jsonb_build_object('id_empleado', t.id_empleado, 'activo', v_activo, 'auth_user_id', t.auth_user_id);
end $$;

