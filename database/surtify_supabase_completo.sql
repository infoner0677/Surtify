-- ---------- Resumen de caja (agrega abonos de fiados) ----------
create or replace function app.resumen_sesion(p_id integer) returns jsonb
language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'id_sesion', s.id_sesion,
    'estado', s.estado_caja,
    'fecha_apertura', s.fecha_apertura,
    'fecha_cierre', s.fecha_cierre,
    'monto_apertura', s.monto_apertura,
    'monto_cierre_esperado', coalesce(s.monto_cierre_esperado, s.monto_apertura),
    'monto_cierre_real', s.monto_cierre_real,
    'diferencia', case when s.monto_cierre_real is null then null
                       else s.monto_cierre_real - coalesce(s.monto_cierre_esperado, s.monto_apertura) end,
    'num_ventas', (select count(*) from movimientos_caja m where m.id_sesion = s.id_sesion and m.tipo_movimiento = 'Ingreso'),
    'total_ventas', coalesce((select sum(monto_neto) from movimientos_caja m where m.id_sesion = s.id_sesion and m.tipo_movimiento = 'Ingreso'), 0),
    'ventas_por_metodo', coalesce((select jsonb_object_agg(metodo_pago, t) from
        (select metodo_pago, sum(monto_neto) t from movimientos_caja m
          where m.id_sesion = s.id_sesion and m.tipo_movimiento = 'Ingreso' group by metodo_pago) x), '{}'::jsonb),
    'total_gastos', coalesce((select sum(monto_gasto) from gastos_caja g where g.id_sesion = s.id_sesion), 0),
    'total_devoluciones', coalesce((select sum(monto_neto) from movimientos_caja m where m.id_sesion = s.id_sesion and m.tipo_movimiento = 'Egreso'), 0),
    'total_abonos', coalesce((select sum(monto) from cartera_movimientos c where c.id_sesion = s.id_sesion and c.tipo = 'Abono'), 0),
    'abonos_efectivo', coalesce((select sum(monto) from cartera_movimientos c where c.id_sesion = s.id_sesion and c.tipo = 'Abono' and c.metodo_pago = 'Efectivo'), 0)
  ) from sesiones_caja s where s.id_sesion = p_id
$$;

-- ---------- Venta (ahora acepta método Fiado) ----------
create or replace function public.registrar_venta(
  p_items jsonb, p_metodo_pago text, p_monto_recibido numeric default null,
  p_id_cliente integer default null, p_canal text default 'POS') returns jsonb
language plpgsql security definer set search_path = public as $$
declare
  v_emp integer := app.mi_empleado(); v_suc integer := app.mi_sucursal(); v_com integer := app.mi_comercio();
  v_ses integer; v_lineas jsonb; l jsonb;
  v_total numeric(12,2) := 0; v_sub numeric(12,2) := 0; v_imp numeric(12,2) := 0;
  v_tl numeric(12,2); v_base numeric(12,2);
  v_recibido numeric(12,2); v_cambio numeric(12,2) := 0;
  v_saldo numeric(12,2); v_cupo numeric(12,2);
  v_pedido integer; v_factura integer; v_pref text; v_cons integer; v_num text; v_fecha timestamptz;
begin
  if v_emp is null then raise exception 'Tu usuario no está vinculado a un empleado activo' using errcode = '42501'; end if;
  select id_sesion into v_ses from sesiones_caja
   where id_empleado = v_emp and estado_caja = 'Abierta' order by fecha_apertura desc limit 1;
  if v_ses is null then raise exception 'Debes abrir la caja antes de vender'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'El carrito está vacío';
  end if;
  if p_metodo_pago not in ('Efectivo','Nequi','Daviplata','Bre-B','Tarjeta','Fiado') then
    raise exception 'Método de pago no válido: %', p_metodo_pago;
  end if;
  if p_id_cliente is not null and not exists (select 1 from clientes where id_cliente = p_id_cliente and id_comercio = v_com) then
    raise exception 'Cliente no válido';
  end if;
  if p_metodo_pago = 'Fiado' and p_id_cliente is null then raise exception 'Elige el cliente al que le fías'; end if;

  -- Normaliza el carrito (agrupa productos repetidos) y trae precio/IVA reales del catálogo
  select jsonb_agg(jsonb_build_object('id_producto', i.id_producto, 'cantidad', i.cant, 'nombre', p.nombre,
                                      'precio', p.precio_venta, 'iva', p.iva_porcentaje))
    into v_lineas
    from (select (x->>'id_producto')::integer as id_producto, sum((x->>'cantidad')::integer) as cant
            from jsonb_array_elements(p_items) x group by 1) i
    left join productos p on p.id_producto = i.id_producto and p.id_comercio = v_com and p.activo;

  for l in select * from jsonb_array_elements(v_lineas) loop
    if l->>'nombre' is null then raise exception 'El producto % no existe o no pertenece a tu comercio', l->>'id_producto'; end if;
    if (l->>'cantidad')::integer <= 0 then raise exception 'Cantidad no válida para el producto %', l->>'nombre'; end if;
    v_total := v_total + (l->>'cantidad')::integer * (l->>'precio')::numeric;
  end loop;

  if p_metodo_pago = 'Efectivo' then
    v_recibido := coalesce(p_monto_recibido, v_total);
    if v_recibido < v_total then raise exception 'El efectivo recibido ($%) es menor al total ($%)', v_recibido, v_total; end if;
    v_cambio := v_recibido - v_total;
  else
    v_recibido := v_total;
  end if;

  if p_metodo_pago = 'Fiado' then   -- bloquea al cliente para que dos ventas simultáneas no superen su cupo
    select cupo_fiado into v_cupo from clientes where id_cliente = p_id_cliente for update;
    select coalesce(sum(case when tipo = 'Cargo' then monto else -monto end), 0) into v_saldo
      from cartera_movimientos where id_cliente = p_id_cliente;
    if v_cupo is not null and v_saldo + v_total > v_cupo then
      raise exception 'Supera el cupo de fiado del cliente (cupo $%, debe $%)', v_cupo, v_saldo;
    end if;
  end if;

  insert into pedidos (id_sucursal, id_cliente, id_empleado, total, estado, canal_venta)
  values (v_suc, p_id_cliente, v_emp, v_total, 'Completado', p_canal) returning id_pedido into v_pedido;

  -- El trigger tr_actualizar_stock_venta descuenta inventario (y aborta todo si no alcanza)
  for l in select * from jsonb_array_elements(v_lineas) loop
    insert into detalles_pedido (id_pedido, id_producto, cantidad, precio_unitario)
    values (v_pedido, (l->>'id_producto')::integer, (l->>'cantidad')::integer, (l->>'precio')::numeric);
    v_tl   := (l->>'cantidad')::integer * (l->>'precio')::numeric;
    v_base := round(v_tl / (1 + (l->>'iva')::numeric / 100), 2);   -- precios con IVA incluido
    v_sub  := v_sub + v_base;
    v_imp  := v_imp + (v_tl - v_base);
  end loop;

  update comercios set consecutivo_factura = consecutivo_factura + 1 where id_comercio = v_com
    returning prefijo_factura, consecutivo_factura into v_pref, v_cons;
  v_num := v_pref || '-' || lpad(v_cons::text, 4, '0');

  -- El trigger tr_registrar_movimiento_factura registra el ingreso y el efectivo esperado
  insert into facturas (id_pedido, numero_factura, subtotal, impuestos, total_facturado, metodo_pago, monto_recibido, monto_cambio)
  values (v_pedido, v_num, v_sub, v_imp, v_total, p_metodo_pago, v_recibido, v_cambio)
  returning id_factura, fecha_emision into v_factura, v_fecha;

  if p_metodo_pago = 'Fiado' then
    insert into cartera_movimientos (id_comercio, id_cliente, id_sucursal, id_empleado, id_sesion, tipo, monto, metodo_pago, id_factura, nota)
    values (v_com, p_id_cliente, v_suc, v_emp, v_ses, 'Cargo', v_total, 'Fiado', v_factura, 'Venta ' || v_num);
  end if;

  for l in select * from jsonb_array_elements(v_lineas) loop
    insert into detalles_factura (id_factura, id_producto, nombre_producto_historico, cantidad, precio_unitario, iva_aplicado, total_linea)
    values (v_factura, (l->>'id_producto')::integer, l->>'nombre', (l->>'cantidad')::integer,
            (l->>'precio')::numeric, (l->>'iva')::numeric, (l->>'cantidad')::integer * (l->>'precio')::numeric);
  end loop;

  return jsonb_build_object('id_pedido', v_pedido, 'id_factura', v_factura, 'numero_factura', v_num,
    'fecha_emision', v_fecha, 'subtotal', v_sub, 'impuestos', v_imp, 'total', v_total,
    'metodo_pago', p_metodo_pago, 'monto_recibido', v_recibido, 'cambio', v_cambio, 'lineas', v_lineas,
    'id_cliente', p_id_cliente, 'saldo_cliente', case when p_metodo_pago = 'Fiado' then v_saldo + v_total end);
end $$;

-- ---------- Devolución (si la venta fue fiada, baja la deuda) ----------
create or replace function public.registrar_devolucion(p_id_factura integer, p_items jsonb, p_motivo text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_emp integer := app.mi_empleado(); v_com integer := app.mi_comercio(); v_ses integer;
  v_f record; v_d jsonb; l jsonb; v_line jsonb; v_lineas jsonb := '[]'::jsonb; v_total numeric(12,2) := 0;
  v_pid integer; v_cant integer; v_precio numeric(12,2); v_nc integer; v_pref text; v_cons integer; v_num text;
  v_motivo text := btrim(coalesce(p_motivo, ''));
begin
  if v_emp is null then raise exception 'Tu usuario no está vinculado a un empleado activo' using errcode = '42501'; end if;
  if v_motivo = '' then raise exception 'Indica el motivo de la devolución'; end if;
  if length(v_motivo) > 255 then raise exception 'El motivo es demasiado largo'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 then
    raise exception 'Selecciona al menos un producto a devolver'; end if;

  select id_sesion into v_ses from sesiones_caja where id_empleado = v_emp and estado_caja = 'Abierta' limit 1;
  if v_ses is null then raise exception 'Abre tu caja antes de registrar una devolución'; end if;

  select f.id_factura, f.metodo_pago, p.id_sucursal, p.id_cliente into v_f
    from facturas f join pedidos p on p.id_pedido = f.id_pedido where f.id_factura = p_id_factura for update of f;
  if not found or not app.puede_ver_sucursal(v_f.id_sucursal) then raise exception 'Factura no encontrada'; end if;

  v_d := public.devolucion_disponible(p_id_factura);   -- se calcula tras bloquear la factura

  for l in select jsonb_build_object('id_producto', (x->>'id_producto')::integer, 'cantidad', sum((x->>'cantidad')::integer))
             from jsonb_array_elements(p_items) x group by (x->>'id_producto')::integer loop
    v_pid := (l->>'id_producto')::integer; v_cant := (l->>'cantidad')::integer;
    if v_cant is null or v_cant <= 0 then raise exception 'Cantidad no válida'; end if;
    select e into v_line from jsonb_array_elements(v_d->'lineas') e where (e->>'id_producto')::integer = v_pid;
    if v_line is null then raise exception 'El producto % no pertenece a esa factura', v_pid; end if;
    if v_cant > (v_line->>'disponible')::integer then
      raise exception 'No puedes devolver % unidades de %: solo quedan % por devolver', v_cant, v_line->>'nombre', v_line->>'disponible';
    end if;
    v_precio := (v_line->>'precio')::numeric;
    v_total := v_total + v_cant * v_precio;
    v_lineas := v_lineas || jsonb_build_object('id_producto', v_pid, 'nombre', v_line->>'nombre', 'cantidad', v_cant,
                                               'precio', v_precio, 'total', v_cant * v_precio);
  end loop;

  update comercios set consecutivo_nota = consecutivo_nota + 1 where id_comercio = v_com
    returning prefijo_factura, consecutivo_nota into v_pref, v_cons;
  v_num := 'NC-' || v_pref || '-' || lpad(v_cons::text, 4, '0');

  -- El trigger tr_registrar_egreso_nota_credito saca el dinero de MI caja abierta
  insert into notas_credito (id_factura, numero_nota, motivo_dian, total_reversado, id_empleado)
  values (p_id_factura, v_num, v_motivo, v_total, v_emp) returning id_nota_credito into v_nc;

  -- El trigger tr_reversar_stock_devolucion reingresa el stock a la sede de la venta original
  for l in select * from jsonb_array_elements(v_lineas) loop
    insert into detalles_nota_credito (id_nota_credito, id_producto, cantidad_devuelta, precio_unitario_reversado, total_linea_reversado)
    values (v_nc, (l->>'id_producto')::integer, (l->>'cantidad')::integer, (l->>'precio')::numeric, (l->>'total')::numeric);
  end loop;

  if v_f.metodo_pago = 'Fiado' and v_f.id_cliente is not null then   -- la devolución de una venta fiada baja la deuda, no sale efectivo
    insert into cartera_movimientos (id_comercio, id_cliente, id_sucursal, id_empleado, id_sesion, tipo, monto, metodo_pago, id_factura, id_nota_credito, nota)
    values (v_com, v_f.id_cliente, app.mi_sucursal(), v_emp, v_ses, 'Nota crédito', v_total, 'Fiado', p_id_factura, v_nc, 'Devolución ' || v_num);
  end if;

  return jsonb_build_object('a_fiado', v_f.metodo_pago = 'Fiado', 'id_nota_credito', v_nc, 'numero_nota', v_num, 'total', v_total, 'metodo_pago', v_f.metodo_pago,
    'efectivo_a_entregar', case when v_f.metodo_pago = 'Efectivo' then v_total else 0 end,
    'lineas', v_lineas, 'caja', app.resumen_sesion(v_ses));
end $$;

-- ---------- Reporte para el contador (abonos y total por cobrar) ----------
create or replace function public.reporte_contador(p_desde date, p_hasta date, p_id_sucursal integer default null)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v_emp integer := app.mi_empleado(); v_com integer := app.mi_comercio(); v_adm boolean := app.es_admin(); v_suc integer := app.mi_sucursal();
  v_sucs integer[]; v_nombre_suc text; res jsonb;
begin
  if v_emp is null then raise exception 'Tu usuario no está vinculado a un empleado activo' using errcode = '42501'; end if;
  if p_desde is null or p_hasta is null or p_desde > p_hasta then raise exception 'El rango de fechas no es válido'; end if;
  if p_hasta - p_desde > 366 then raise exception 'El rango máximo es de un año'; end if;

  -- Administrador: todas las sedes (o la elegida). Cajero: solo la suya.
  select array_agg(s.id_sucursal) into v_sucs from sucursales s
   where s.id_comercio = v_com
     and ((v_adm and (p_id_sucursal is null or s.id_sucursal = p_id_sucursal)) or (not v_adm and s.id_sucursal = v_suc));
  if v_sucs is null then raise exception 'Sucursal no válida'; end if;
  if array_length(v_sucs, 1) = 1 then select nombre_sucursal into v_nombre_suc from sucursales where id_sucursal = v_sucs[1]; end if;

  with f as (
    select fa.id_factura, fa.numero_factura, fa.fecha_emision, fa.subtotal, fa.impuestos, fa.total_facturado,
           fa.metodo_pago, fa.estado_dian, s.nombre_sucursal as sucursal
      from facturas fa
      join pedidos p on p.id_pedido = fa.id_pedido
      join sucursales s on s.id_sucursal = p.id_sucursal
     where p.id_sucursal = any(v_sucs)
       and (fa.fecha_emision at time zone 'America/Bogota')::date between p_desde and p_hasta
  ), n as (
    select nc.id_nota_credito, nc.numero_nota, nc.fecha_emision, nc.total_reversado, nc.motivo_dian,
           fa.numero_factura, s.nombre_sucursal as sucursal
      from notas_credito nc
      join facturas fa on fa.id_factura = nc.id_factura
      join pedidos p on p.id_pedido = fa.id_pedido
      join sucursales s on s.id_sucursal = p.id_sucursal
     where p.id_sucursal = any(v_sucs)
       and (nc.fecha_emision at time zone 'America/Bogota')::date between p_desde and p_hasta
  ), l as (
    select df.iva_aplicado, df.total_linea, round(df.total_linea / (1 + df.iva_aplicado / 100), 2) as base
      from detalles_factura df join f on f.id_factura = df.id_factura
  )
  select jsonb_build_object(
    'comercio', (select jsonb_build_object('nombre', c.nombre_comercial, 'razon_social', c.razon_social, 'nit', c.nit_rut)
                   from comercios c where c.id_comercio = v_com),
    'desde', p_desde, 'hasta', p_hasta, 'sucursal', v_nombre_suc,
    'facturas', (select jsonb_build_object('num', count(*), 'total', coalesce(sum(total_facturado), 0),
                   'subtotal', coalesce(sum(subtotal), 0), 'iva', coalesce(sum(impuestos), 0),
                   'primera', (select numero_factura from f order by id_factura limit 1),
                   'ultima',  (select numero_factura from f order by id_factura desc limit 1)) from f),
    'iva_por_tarifa', coalesce((select jsonb_agg(jsonb_build_object('tarifa', iva_aplicado, 'base', b, 'iva', i, 'total', t) order by iva_aplicado)
                         from (select iva_aplicado, sum(base) as b, sum(total_linea - base) as i, sum(total_linea) as t from l group by iva_aplicado) x), '[]'::jsonb),
    'devoluciones', (select jsonb_build_object('num', count(*), 'total', coalesce(sum(total_reversado), 0)) from n),
    'ventas_netas', (select coalesce(sum(total_facturado), 0) from f) - (select coalesce(sum(total_reversado), 0) from n),
    'por_metodo', coalesce((select jsonb_object_agg(metodo_pago, t) from (select metodo_pago, sum(total_facturado) as t from f group by metodo_pago) x), '{}'::jsonb),
    'gastos', coalesce((select sum(g.monto_gasto) from gastos_caja g
                   join sesiones_caja sc on sc.id_sesion = g.id_sesion
                  where sc.id_sucursal = any(v_sucs) and (v_adm or sc.id_empleado = v_emp)
                    and (g.fecha_gasto at time zone 'America/Bogota')::date between p_desde and p_hasta), 0),
    'abonos_cartera', coalesce((select sum(cm.monto) from cartera_movimientos cm
                  where cm.tipo = 'Abono' and cm.id_comercio = v_com and cm.id_sucursal = any(v_sucs)
                    and (cm.fecha at time zone 'America/Bogota')::date between p_desde and p_hasta), 0),
    'por_cobrar', coalesce((select sum(case when cm.tipo = 'Cargo' then cm.monto else -cm.monto end)
                  from cartera_movimientos cm where cm.id_comercio = v_com and cm.id_sucursal = any(v_sucs)), 0),
    'por_sucursal', coalesce((select jsonb_agg(jsonb_build_object('nombre', sucursal, 'num', num, 'total', total) order by sucursal)
                       from (select sucursal, count(*) as num, sum(total_facturado) as total from f group by sucursal) x), '[]'::jsonb),
    'detalle_facturas', coalesce((select jsonb_agg(jsonb_build_object('numero', numero_factura, 'fecha', fecha_emision, 'sucursal', sucursal,
                          'metodo', metodo_pago, 'subtotal', subtotal, 'iva', impuestos, 'total', total_facturado, 'estado_dian', estado_dian) order by id_factura)
                       from (select * from f order by id_factura limit 2000) z), '[]'::jsonb),
    'detalle_notas', coalesce((select jsonb_agg(jsonb_build_object('numero', numero_nota, 'fecha', fecha_emision, 'factura', numero_factura,
                          'sucursal', sucursal, 'motivo', motivo_dian, 'total', total_reversado) order by id_nota_credito)
                       from (select * from n order by id_nota_credito limit 2000) z), '[]'::jsonb)
  ) into res;
  return res;
end $$;

-- ---------- Crear cliente ----------
create or replace function public.crear_cliente(p_nombre text, p_telefono text default null,
                                                p_cedula text default null, p_cupo numeric default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_tel text; v_id integer; v_ced text := nullif(btrim(coalesce(p_cedula, '')), '');
begin
  if app.mi_empleado() is null then raise exception 'Tu usuario no está vinculado a un empleado activo' using errcode = '42501'; end if;
  if btrim(coalesce(p_nombre, '')) = '' then raise exception 'Escribe el nombre del cliente'; end if;
