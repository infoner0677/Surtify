-- ---------- Festivos de Colombia (se calculan, no se escriben a mano) ----------
create or replace function app.pascua(p_anio integer) returns date language sql immutable as $$
  with t as (select p_anio as y, p_anio % 19 as a, p_anio / 100 as b, p_anio % 100 as c),
       u as (select *, b / 4 as d, b % 4 as e, (b + 8) / 25 as f, c / 4 as i, c % 4 as k from t),
       v as (select *, (b - f + 1) / 3 as g from u),
       w as (select *, (19 * a + b - d - g + 15) % 30 as h from v),
       x as (select *, (32 + 2 * e + 2 * i - h - k) % 7 as l from w),
       z as (select *, (a + 11 * h + 22 * l) / 451 as m from x)
  select make_date(y, (h + l - 7 * m + 114) / 31, ((h + l - 7 * m + 114) % 31) + 1) from z
$$;

create or replace function app.es_festivo_co(p_dia date) returns boolean language plpgsql immutable as $$
declare y integer := extract(year from p_dia)::integer; pas date := app.pascua(y); f date;
begin
  if (p_dia = make_date(y, 1, 1) or p_dia = make_date(y, 5, 1) or p_dia = make_date(y, 7, 20) or p_dia = make_date(y, 8, 7)
      or p_dia = make_date(y, 12, 8) or p_dia = make_date(y, 12, 25) or p_dia = pas - 3 or p_dia = pas - 2) then return true; end if;
  -- trasladables al lunes: Reyes, San José, San Pedro y San Pablo, Asunción, Raza, Todos los Santos, Independencia de Cartagena
  foreach f in array array[make_date(y, 1, 6), make_date(y, 3, 19), make_date(y, 6, 29), make_date(y, 8, 15), make_date(y, 10, 12), make_date(y, 11, 1), make_date(y, 11, 11),
                           pas + 39, pas + 60, pas + 68] loop
    if p_dia = f + ((8 - extract(isodow from f)::integer) % 7) then return true; end if;
  end loop;
  return false;
end $$;

-- ¿Se puede contactar para cobrar ahora? (hora de Colombia)
create or replace function app.ventana_cobranza(p_ahora timestamptz default now())
returns jsonb language plpgsql stable as $$
declare l timestamp := p_ahora at time zone 'America/Bogota'; d date := l::date; dow integer := extract(isodow from l)::integer; h numeric := extract(hour from l) + extract(minute from l) / 60;
        ini numeric; fin numeric;
begin
  if dow = 7 then return jsonb_build_object('ok', false, 'motivo', 'Hoy es domingo: no se envían recordatorios. Vuelve el lunes desde las 7:00 a. m.'); end if;
  if app.es_festivo_co(d) then return jsonb_build_object('ok', false, 'motivo', 'Hoy es festivo: no se envían recordatorios.'); end if;
  if dow = 6 then ini := 8; fin := 15; else ini := 7; fin := 19; end if;
  if h < ini then return jsonb_build_object('ok', false, 'motivo', format('Todavía es temprano: los recordatorios se envían desde las %s:00 a. m.', ini::int)); end if;
  if h >= fin then return jsonb_build_object('ok', false, 'motivo', 'Ya pasó el horario de hoy: los recordatorios se envían de lunes a viernes de 7:00 a. m. a 7:00 p. m. y sábados de 8:00 a. m. a 3:00 p. m.'); end if;
  return jsonb_build_object('ok', true);
end $$;

-- ---------- Candidatos (interno) ----------
create or replace function app.recordatorio_candidatos(p_com integer)
returns table (id_cliente integer, nombre text, telefono text, saldo numeric, dias integer, autorizado boolean, ultimo timestamptz, elegible boolean)
language sql stable security definer set search_path = public as $$
  with cfg as (select coalesce(c.dias_inicio, 15) as dias_inicio, coalesce(c.cada_dias, 15) as cada_dias, coalesce(c.monto_minimo, 10000) as monto_minimo
                 from (select 1) x left join recordatorio_config c on c.id_comercio = p_com),
  mov as (select m.id_cliente, sum(case when m.tipo = 'Cargo' then m.monto else -m.monto end) as saldo,
                 coalesce(sum(m.monto) filter (where m.tipo <> 'Cargo'), 0) as abonado
            from cartera_movimientos m where m.id_comercio = p_com group by m.id_cliente),
  cum as (select m.id_cliente, m.fecha, sum(m.monto) over (partition by m.id_cliente order by m.fecha, m.id_movimiento) as acum
            from cartera_movimientos m where m.id_comercio = p_com and m.tipo = 'Cargo'),
  desde as (select cu.id_cliente, min(cu.fecha) as f from cum cu join mov using (id_cliente) where cu.acum > mov.abonado group by cu.id_cliente),
  ult as (select e.id_cliente, max(e.enviado) as u from recordatorios_enviados e where e.id_comercio = p_com group by e.id_cliente)
  select c.id_cliente, c.nombre::text,
         case when length(d.t) = 12 and left(d.t, 2) = '57' then substr(d.t, 3) else d.t end as telefono,
         mov.saldo, floor(extract(epoch from now() - desde.f) / 86400)::integer as dias, c.recordatorios_ok, ult.u,
         (c.recordatorios_ok is true and mov.saldo >= cfg.monto_minimo and now() - desde.f >= make_interval(days => cfg.dias_inicio)
          and (case when length(d.t) = 12 and left(d.t, 2) = '57' then substr(d.t, 3) else d.t end) ~ '^3[0-9]{9}$'
          and (ult.u is null or now() - ult.u >= make_interval(days => greatest(cfg.cada_dias, 7)))) as elegible
    from clientes c cross join cfg
    cross join lateral (select regexp_replace(coalesce(c.telefono, ''), '\D', '', 'g') as t) d
    join mov on mov.id_cliente = c.id_cliente
    join desde on desde.id_cliente = c.id_cliente
    left join ult on ult.id_cliente = c.id_cliente
   where c.id_comercio = p_com and mov.saldo > 0 and c.recordatorios_ok is distinct from false
$$;
revoke all on function app.recordatorio_candidatos(integer) from public, anon, authenticated;

create or replace function app.recordatorio_mensaje(p_plantilla text, p_nombre text, p_tienda text, p_saldo numeric)
returns text language sql immutable as $$
  select replace(replace(replace(p_plantilla, '{nombre}', split_part(btrim(p_nombre), ' ', 1)), '{tienda}', p_tienda),
                 '{saldo}', '$ ' || replace(to_char(p_saldo, 'FM999,999,999,999'), ',', '.'))
$$;

-- ---------- Configuración ----------
create or replace function public.recordatorios_config()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); c recordatorio_config%rowtype;
begin
  if not app.tiene_permiso('fiados') then raise exception 'Tu rol no tiene permiso para esto' using errcode = '42501'; end if;
  select * into c from recordatorio_config where id_comercio = v_com;
  if not found then c.activo := false; c.dias_inicio := 15; c.cada_dias := 15; c.monto_minimo := 10000;
    c.plantilla := 'Hola {nombre}, te escribimos de {tienda}. Tu saldo pendiente es {saldo}. Cuando puedas, nos avisas. ¡Gracias!'; end if;
  return jsonb_build_object('activo', c.activo, 'dias_inicio', c.dias_inicio, 'cada_dias', c.cada_dias, 'monto_minimo', c.monto_minimo, 'plantilla', c.plantilla);
end $$;

create or replace function public.recordatorios_config_guardar(p_activo boolean, p_dias_inicio integer, p_cada_dias integer, p_monto_minimo numeric, p_plantilla text)
returns void language plpgsql security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_pl text := btrim(coalesce(p_plantilla, ''));
begin
  if not app.es_admin() then raise exception 'Solo el administrador puede configurar los recordatorios' using errcode = '42501'; end if;
  if p_dias_inicio is null or p_dias_inicio not between 1 and 365 then raise exception 'Los días para empezar deben estar entre 1 y 365'; end if;
  if p_cada_dias is null or p_cada_dias not between 7 and 90 then raise exception 'Los recordatorios deben espaciarse entre 7 y 90 días (máximo uno por semana)'; end if;
  if p_monto_minimo is null or p_monto_minimo < 0 or p_monto_minimo > 100000000 then raise exception 'El valor mínimo no es válido'; end if;
  if char_length(v_pl) < 10 or char_length(v_pl) > 300 then raise exception 'El mensaje debe tener entre 10 y 300 letras'; end if;
  if v_pl !~* '\{saldo\}' then raise exception 'El mensaje debe incluir {saldo}'; end if;
  if v_pl ~* '(https?://|www\.)' then raise exception 'El mensaje no debe llevar enlaces'; end if;
  insert into recordatorio_config (id_comercio, activo, dias_inicio, cada_dias, monto_minimo, plantilla, actualizado)
    values (v_com, coalesce(p_activo, false), p_dias_inicio, p_cada_dias, p_monto_minimo, v_pl, now())
    on conflict (id_comercio) do update set activo = excluded.activo, dias_inicio = excluded.dias_inicio, cada_dias = excluded.cada_dias,
        monto_minimo = excluded.monto_minimo, plantilla = excluded.plantilla, actualizado = now();
  perform app.equipo_log(v_com, app.mi_empleado(), null, 'recordatorio_config', case when p_activo then 'Recordatorios de cobro activados' else 'Recordatorios de cobro desactivados' end);
end $$;

-- ---------- Autorización del cliente ----------
create or replace function public.cliente_recordatorios(p_id_cliente integer, p_valor boolean)
returns void language plpgsql security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_nom text;
begin
  if not app.tiene_permiso('fiados') then raise exception 'Tu rol no tiene permiso para esto' using errcode = '42501'; end if;
  select nombre into v_nom from clientes where id_cliente = p_id_cliente and id_comercio = v_com;
  if not found then raise exception 'Cliente no válido'; end if;
  update clientes set recordatorios_ok = p_valor where id_cliente = p_id_cliente;
  perform app.equipo_log(v_com, app.mi_empleado(), null, 'recordatorio_cliente',
    case when p_valor is true then v_nom || ' autorizó recordatorios por WhatsApp' when p_valor is false then v_nom || ' no quiere recordatorios' else 'Se quitó la autorización de recordatorios de ' || v_nom end);
end $$;

-- ---------- Lista de hoy ----------
create or replace function public.recordatorios_pendientes()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_cfg jsonb; v_tienda text; v_pl text; v_vent jsonb := app.ventana_cobranza();
begin
  if not app.tiene_permiso('fiados') then raise exception 'Tu rol no tiene permiso para esto' using errcode = '42501'; end if;
  v_cfg := public.recordatorios_config();
  select nombre_comercial into v_tienda from comercios where id_comercio = v_com;
  v_pl := v_cfg->>'plantilla';
  return jsonb_build_object('activo', (v_cfg->>'activo')::boolean, 'ventana', v_vent,
    'items', case when not (v_cfg->>'activo')::boolean then '[]'::jsonb else coalesce((select jsonb_agg(jsonb_build_object(
        'id_cliente', k.id_cliente, 'nombre', k.nombre, 'saldo', k.saldo, 'dias', k.dias, 'ultimo', k.ultimo,
        'mensaje', app.recordatorio_mensaje(v_pl, k.nombre, v_tienda, k.saldo)) order by k.saldo desc) from app.recordatorio_candidatos(v_com) k where k.elegible), '[]'::jsonb) end,
    'sin_autorizacion', case when not (v_cfg->>'activo')::boolean then 0 else (select count(*) from app.recordatorio_candidatos(v_com) k
        where k.autorizado is null and k.saldo >= (v_cfg->>'monto_minimo')::numeric and k.dias >= (v_cfg->>'dias_inicio')::integer) end);
end $$;

-- ---------- Registrar un envío (valida todo de nuevo y devuelve el mensaje y el teléfono) ----------
create or replace function public.recordatorio_registrar(p_id_cliente integer)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_cfg jsonb; v_vent jsonb := app.ventana_cobranza(); k record; v_tienda text;
begin
  if not app.tiene_permiso('fiados') then raise exception 'Tu rol no tiene permiso para esto' using errcode = '42501'; end if;
  v_cfg := public.recordatorios_config();
  if not (v_cfg->>'activo')::boolean then raise exception 'Los recordatorios están desactivados'; end if;
  if not (v_vent->>'ok')::boolean then raise exception '%', v_vent->>'motivo'; end if;
  select * into k from app.recordatorio_candidatos(v_com) c where c.id_cliente = p_id_cliente;
  if not found or not k.elegible then raise exception 'A este cliente no le corresponde un recordatorio ahora (autorización, valor, días o ya se le envió uno esta semana)'; end if;
  select nombre_comercial into v_tienda from comercios where id_comercio = v_com;
  insert into recordatorios_enviados (id_comercio, id_cliente, id_empleado, saldo) values (v_com, p_id_cliente, app.mi_empleado(), k.saldo);
  return jsonb_build_object('telefono', '57' || k.telefono, 'mensaje', app.recordatorio_mensaje(v_cfg->>'plantilla', k.nombre, v_tienda, k.saldo));
end $$;

