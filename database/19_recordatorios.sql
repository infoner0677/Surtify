  v_new := replace(v_def, '''cupo_fiado'', v_cli.cupo_fiado,', '''cupo_fiado'', v_cli.cupo_fiado, ''recordatorios_ok'', (select recordatorios_ok from clientes where id_cliente = p_id_cliente),');
