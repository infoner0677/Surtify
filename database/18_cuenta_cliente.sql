-- =============================================================================
-- SURTIFY · 18_cuenta_cliente.sql
--   "Mi cuenta": el cliente que fía ve su deuda (saldo, cupo, desde cuándo, compras con detalle y abonos).
--   Dos formas de entrar, ambas pensadas para ser seguras:
--     A) Google. Los clientes del autoservicio ya entran así. A un cliente que el tendero creó a mano se le da un
--        CÓDIGO DE VINCULACIÓN de un solo uso (8 caracteres, vence en 7 días); lo escribe una vez con su sesión de Google.
--     B) ENLACE PERSONAL + PIN de 6 dígitos (para quien no usa Google). El enlace lleva un secreto largo (192 bits) en
--        el fragmento de la URL (no viaja al servidor) y el PIN se entrega aparte. Vence en 90 días, se puede revocar.
--   Seguridad:
--     * Nada se guarda en claro: enlace y código se guardan como SHA-256; el PIN con bcrypt.
--     * Intentos limitados: PIN → bloqueo de 15 min cada 5 fallos y se revoca el enlace a los 15; código → 5 fallos/hora.
--     * Respuestas genéricas (no revelan si un enlace existe). Un cliente solo ve SU cuenta.
--     * Las tablas no son accesibles desde el cliente: todo pasa por funciones que validan.
--   El tendero (permiso «fiados») genera/revoca accesos; queda registro en equipo_eventos.
-- =============================================================================
create table if not exists cliente_accesos (
  id_acceso      bigint generated by default as identity primary key,
  id_comercio    integer not null references comercios(id_comercio) on delete cascade,
  id_cliente     integer not null references clientes(id_cliente) on delete cascade,
  tipo           text not null check (tipo in ('enlace', 'codigo')),
  secreto_hash   bytea not null,
  pin_hash       text,
  intentos       integer not null default 0,
  bloqueado_hasta timestamptz,
  expira         timestamptz not null,
  usado_en       timestamptz,
  ultimo_uso     timestamptz,
  revocado       boolean not null default false,
  creado_por     integer references empleados(id_empleado) on delete set null,
  creado         timestamptz not null default now()
);
create unique index if not exists cliente_accesos_secreto_uq on cliente_accesos (secreto_hash);
create index if not exists cliente_accesos_cliente_idx on cliente_accesos (id_cliente);
alter table cliente_accesos enable row level security;
revoke all on cliente_accesos from anon, authenticated;

create table if not exists cliente_vinculo_intentos (
  id_intento   bigint generated by default as identity primary key,
  auth_user_id uuid not null,
  creado       timestamptz not null default now()
);
create index if not exists cliente_vinculo_int_idx on cliente_vinculo_intentos (auth_user_id, creado desc);
alter table cliente_vinculo_intentos enable row level security;
revoke all on cliente_vinculo_intentos from anon, authenticated;

-- ---------- Resumen de la cuenta de un cliente (interno) ----------
create or replace function app.cuenta_cliente(p_id integer)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare c record; v_saldo numeric; v_abonado numeric; v_desde timestamptz; v_pago jsonb;
begin
  select cl.id_cliente, cl.id_comercio, cl.nombre, cl.cupo_fiado, co.nombre_comercial into c
    from clientes cl join comercios co on co.id_comercio = cl.id_comercio where cl.id_cliente = p_id;
  if not found then return null; end if;
  select coalesce(sum(case when tipo = 'Cargo' then monto else -monto end), 0),
         coalesce(sum(case when tipo <> 'Cargo' then monto else 0 end), 0) into v_saldo, v_abonado
    from cartera_movimientos where id_cliente = p_id;
  -- Desde cuándo debe: la compra más antigua que los abonos aún no cubren (los abonos se aplican a lo más viejo primero)
  select min(q.fecha) into v_desde from (
    select fecha, sum(monto) over (order by fecha, id_movimiento) as acum
      from cartera_movimientos where id_cliente = p_id and tipo = 'Cargo') q where q.acum > v_abonado;
  if v_saldo <= 0 then v_desde := null; end if;
  select jsonb_build_object('llave', s.llave_breb, 'titular', s.titular_breb) into v_pago
    from sucursales s where s.id_comercio = c.id_comercio and s.autoservicio and s.llave_breb is not null order by s.id_sucursal limit 1;
  return jsonb_build_object('comercio', c.nombre_comercial, 'nombre', c.nombre, 'cupo', c.cupo_fiado, 'saldo', v_saldo,
    'disponible', greatest(coalesce(c.cupo_fiado, 0) - v_saldo, 0), 'deuda_desde', v_desde, 'como_pagar', v_pago,
    'movimientos', coalesce((select jsonb_agg(jsonb_build_object('fecha', x.fecha, 'tipo', x.tipo, 'monto', x.monto, 'metodo_pago', x.metodo_pago,
          'factura', x.numero_factura, 'lineas', x.lineas) order by x.fecha desc, x.id_movimiento desc)
        from (select m.*, f.numero_factura,
                     (select jsonb_agg(jsonb_build_object('producto', d.nombre_producto_historico, 'cantidad', d.cantidad, 'total', d.total_linea) order by d.id_detalle_factura)
                        from detalles_factura d where d.id_factura = m.id_factura) as lineas
                from cartera_movimientos m left join facturas f on f.id_factura = m.id_factura
               where m.id_cliente = p_id order by m.fecha desc, m.id_movimiento desc limit 60) x), '[]'::jsonb));
end $$;
revoke all on function app.cuenta_cliente(integer) from public, anon, authenticated;

-- ---------- Tendero: generar un acceso ----------
create or replace function public.cliente_acceso_crear(p_id_cliente integer, p_tipo text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_nom text; v_sec text; v_pin text; v_alf constant text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789'; v_b bytea; i int;
begin
  if not app.tiene_permiso('fiados') then raise exception 'Tu rol no tiene permiso para esto' using errcode = '42501'; end if;
  if p_tipo not in ('enlace', 'codigo') then raise exception 'Tipo de acceso no válido'; end if;
  select nombre into v_nom from clientes where id_cliente = p_id_cliente and id_comercio = v_com;
  if not found then raise exception 'Cliente no válido'; end if;
  if p_tipo = 'codigo' and exists (select 1 from clientes_autoservicio where id_cliente = p_id_cliente and estado <> 'Rechazado') then
    raise exception 'Este cliente ya tiene su cuenta de Google vinculada';
  end if;
  update cliente_accesos set revocado = true where id_cliente = p_id_cliente and tipo = p_tipo and not revocado and usado_en is null;
  if p_tipo = 'enlace' then
    v_sec := encode(extensions.gen_random_bytes(24), 'hex');
    v_pin := lpad(((('x' || encode(extensions.gen_random_bytes(4), 'hex'))::bit(32)::bigint) % 1000000)::text, 6, '0');
    insert into cliente_accesos (id_comercio, id_cliente, tipo, secreto_hash, pin_hash, expira, creado_por)
      values (v_com, p_id_cliente, 'enlace', extensions.digest(convert_to(v_sec, 'utf8'), 'sha256'), extensions.crypt(v_pin, extensions.gen_salt('bf', 8)),
              now() + interval '90 days', app.mi_empleado());
    perform app.equipo_log(v_com, app.mi_empleado(), null, 'cliente_acceso', 'Enlace de cuenta para ' || v_nom);
    return jsonb_build_object('tipo', 'enlace', 'token', v_sec, 'pin', v_pin, 'expira', now() + interval '90 days');
  end if;
  v_b := extensions.gen_random_bytes(8); v_sec := '';
  for i in 0..7 loop v_sec := v_sec || substr(v_alf, (get_byte(v_b, i) % 31) + 1, 1); end loop;
  insert into cliente_accesos (id_comercio, id_cliente, tipo, secreto_hash, expira, creado_por)
    values (v_com, p_id_cliente, 'codigo', extensions.digest(convert_to(v_sec, 'utf8'), 'sha256'), now() + interval '7 days', app.mi_empleado());
  perform app.equipo_log(v_com, app.mi_empleado(), null, 'cliente_acceso', 'Código de vinculación para ' || v_nom);
  return jsonb_build_object('tipo', 'codigo', 'codigo', substr(v_sec, 1, 4) || '-' || substr(v_sec, 5, 4), 'expira', now() + interval '7 days');
end $$;

-- ---------- Tendero: ver y revocar ----------
create or replace function public.cliente_acceso_estado(p_id_cliente integer)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); e record; c record; g text;
begin
  if not app.tiene_permiso('fiados') then raise exception 'Tu rol no tiene permiso para esto' using errcode = '42501'; end if;
  if not exists (select 1 from clientes where id_cliente = p_id_cliente and id_comercio = v_com) then raise exception 'Cliente no válido'; end if;
  select estado into g from clientes_autoservicio where id_cliente = p_id_cliente;
  select expira, ultimo_uso, (bloqueado_hasta > now()) as bloqueado into e from cliente_accesos
   where id_cliente = p_id_cliente and tipo = 'enlace' and not revocado and expira > now() order by creado desc limit 1;
  select expira into c from cliente_accesos
   where id_cliente = p_id_cliente and tipo = 'codigo' and not revocado and usado_en is null and expira > now() order by creado desc limit 1;
  return jsonb_build_object('google', g,
    'enlace', case when e.expira is null then null else jsonb_build_object('expira', e.expira, 'ultimo_uso', e.ultimo_uso, 'bloqueado', coalesce(e.bloqueado, false)) end,
    'codigo', case when c.expira is null then null else jsonb_build_object('expira', c.expira) end);
end $$;

create or replace function public.cliente_acceso_revocar(p_id_cliente integer, p_que text)
returns void language plpgsql security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); v_nom text;
begin
  if not app.tiene_permiso('fiados') then raise exception 'Tu rol no tiene permiso para esto' using errcode = '42501'; end if;
  if p_que not in ('enlace', 'codigo', 'google', 'todo') then raise exception 'Opción no válida'; end if;
  select nombre into v_nom from clientes where id_cliente = p_id_cliente and id_comercio = v_com;
  if not found then raise exception 'Cliente no válido'; end if;
  if p_que in ('enlace', 'codigo', 'todo') then
    update cliente_accesos set revocado = true where id_cliente = p_id_cliente and not revocado and (p_que = 'todo' or tipo = p_que);
  end if;
  if p_que in ('google', 'todo') then
    update clientes_autoservicio set estado = 'Rechazado', resuelto = now(), resuelto_por = app.mi_empleado() where id_cliente = p_id_cliente;
  end if;
  perform app.equipo_log(v_com, app.mi_empleado(), null, 'cliente_acceso', 'Acceso revocado (' || p_que || ') a ' || v_nom);
end $$;

-- ---------- Cliente B: enlace + PIN (sin sesión) ----------
create or replace function public.cuenta_por_enlace(p_token text, p_pin text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare a cliente_accesos%rowtype; v_tok text := btrim(coalesce(p_token, '')); v_n integer;
        v_gen constant jsonb := jsonb_build_object('ok', false, 'error', 'Enlace o PIN incorrecto');
begin
  if v_tok !~ '^[0-9a-f]{48}$' then perform pg_sleep(0.4); return v_gen; end if;
  select * into a from cliente_accesos where tipo = 'enlace' and secreto_hash = extensions.digest(convert_to(v_tok, 'utf8'), 'sha256') for update;
  if not found then perform pg_sleep(0.4); return v_gen; end if;
  if a.revocado then return jsonb_build_object('ok', false, 'error', 'Este enlace ya no está activo. Pídele uno nuevo a tu tienda.'); end if;
  if a.expira < now() then return jsonb_build_object('ok', false, 'error', 'Este enlace venció. Pídele uno nuevo a tu tienda.'); end if;
  if a.bloqueado_hasta is not null and a.bloqueado_hasta > now() then
    return jsonb_build_object('ok', false, 'error', 'Demasiados intentos. Espera unos minutos e inténtalo de nuevo.'); end if;
  if a.pin_hash is null or extensions.crypt(coalesce(p_pin, ''), a.pin_hash) <> a.pin_hash then
    v_n := a.intentos + 1;
    update cliente_accesos set intentos = v_n,
           bloqueado_hasta = case when v_n % 5 = 0 then now() + interval '15 minutes' else bloqueado_hasta end,
           revocado = (v_n >= 15) where id_acceso = a.id_acceso;
    perform pg_sleep(0.4);
    return v_gen;
  end if;
  update cliente_accesos set intentos = 0, bloqueado_hasta = null, ultimo_uso = now() where id_acceso = a.id_acceso;
  return jsonb_build_object('ok', true, 'cuenta', app.cuenta_cliente(a.id_cliente));
end $$;

-- ---------- Cliente A: Google ----------
create or replace function public.cuenta_vincular_codigo(p_codigo text, p_acepta boolean)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); u record; v_cod text := upper(regexp_replace(coalesce(p_codigo, ''), '[^A-Za-z0-9]', '', 'g')); a cliente_accesos%rowtype;
begin
  if v_uid is null then raise exception 'Inicia sesión'; end if;
  if not coalesce(p_acepta, false) then raise exception 'Debes autorizar el tratamiento de tus datos'; end if;
  select email, email_confirmed_at into u from auth.users where id = v_uid;
  if u.email is null or u.email_confirmed_at is null then raise exception 'Tu correo no está verificado'; end if;
  if (select count(*) from cliente_vinculo_intentos where auth_user_id = v_uid and creado > now() - interval '1 hour') >= 5 then
    return jsonb_build_object('ok', false, 'error', 'Demasiados intentos. Inténtalo de nuevo en una hora.'); end if;
  select * into a from cliente_accesos where tipo = 'codigo' and secreto_hash = extensions.digest(convert_to(v_cod, 'utf8'), 'sha256')
     and not revocado and usado_en is null and expira > now() for update;
  if not found then
    insert into cliente_vinculo_intentos (auth_user_id) values (v_uid);
    perform pg_sleep(0.4);
    return jsonb_build_object('ok', false, 'error', 'Código incorrecto o vencido. Pídele uno nuevo a tu tienda.');
  end if;
  if exists (select 1 from clientes_autoservicio where id_cliente = a.id_cliente) then
    return jsonb_build_object('ok', false, 'error', 'Este cliente ya tiene una cuenta de Google vinculada.'); end if;
  if exists (select 1 from clientes_autoservicio where auth_user_id = v_uid and id_comercio = a.id_comercio) then
    return jsonb_build_object('ok', false, 'error', 'Tu cuenta de Google ya está vinculada a otro cliente de esta tienda.'); end if;
  insert into clientes_autoservicio (id_cliente, id_comercio, auth_user_id, email, estado, acepta_datos_en, resuelto, resuelto_por)
    values (a.id_cliente, a.id_comercio, v_uid, u.email, 'Aprobado', now(), now(), a.creado_por);
  update clientes set email = coalesce(email, u.email) where id_cliente = a.id_cliente;
  update cliente_accesos set usado_en = now() where id_acceso = a.id_acceso;
  perform app.equipo_log(a.id_comercio, null, null, 'cliente_acceso', 'Cliente vinculó su cuenta de Google (' || u.email || ')');
  return jsonb_build_object('ok', true);
end $$;

create or replace function public.cuenta_google()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_uid uuid := auth.uid();
begin
  if v_uid is null then raise exception 'Inicia sesión'; end if;
  return jsonb_build_object('cuentas', coalesce((select jsonb_agg(
      case when ca.estado = 'Aprobado' then app.cuenta_cliente(ca.id_cliente) || jsonb_build_object('estado', ca.estado)
           else jsonb_build_object('estado', ca.estado, 'comercio', co.nombre_comercial) end order by ca.creado)
    from clientes_autoservicio ca join comercios co on co.id_comercio = ca.id_comercio where ca.auth_user_id = v_uid and ca.estado <> 'Rechazado'), '[]'::jsonb));
end $$;

do $$ declare f text; begin
  foreach f in array array['cliente_acceso_crear(integer,text)', 'cliente_acceso_estado(integer)', 'cliente_acceso_revocar(integer,text)',
                           'cuenta_por_enlace(text,text)', 'cuenta_vincular_codigo(text,boolean)', 'cuenta_google()'] loop
    execute format('revoke all on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
  grant execute on function public.cuenta_por_enlace(text, text) to anon;
end $$;
