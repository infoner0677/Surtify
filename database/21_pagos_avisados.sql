-- =============================================================================
-- SURTIFY · 21_pagos_avisados.sql
--   "Avisar mi pago": el cliente (desde Mi cuenta, con Google o con enlace + PIN) avisa que ya pagó (valor, método y
--   referencia). NO cambia su deuda: queda como aviso pendiente y el tendero lo confirma (se registra el abono con
--   registrar_abono, a su nombre y en su caja) o lo rechaza con un motivo. El cliente ve el estado de su aviso.
--   Reglas: valor > 0 y no mayor al saldo pendiente (contando avisos en revisión), máx. 3 avisos en revisión y 10 por día,
--   referencia (opcional) única por tienda mientras no sea rechazada.
-- =============================================================================
create table if not exists pagos_avisados (
  id_aviso      bigint generated by default as identity primary key,
  id_comercio   integer not null references comercios(id_comercio) on delete cascade,
  id_cliente    integer not null references clientes(id_cliente) on delete cascade,
  monto         numeric(12,2) not null check (monto > 0),
  metodo        text not null check (metodo in ('Bre-B', 'Nequi', 'Daviplata', 'Efectivo', 'Tarjeta')),
  referencia    text check (referencia is null or char_length(referencia) between 3 and 40),
  estado        text not null default 'Pendiente' check (estado in ('Pendiente', 'Confirmado', 'Rechazado')),
  nota_tendero  text check (nota_tendero is null or char_length(nota_tendero) <= 160),
  creado        timestamptz not null default now(),
  resuelto      timestamptz,
  resuelto_por  integer references empleados(id_empleado) on delete set null,
  id_movimiento integer
);
create unique index if not exists pagos_avisados_ref_uq on pagos_avisados (id_comercio, referencia) where referencia is not null and estado <> 'Rechazado';
create index if not exists pagos_avisados_cli_idx on pagos_avisados (id_cliente, creado desc);
create index if not exists pagos_avisados_com_idx on pagos_avisados (id_comercio, estado, creado desc);
alter table pagos_avisados enable row level security;
revoke all on pagos_avisados from anon, authenticated;

-- ---------- Crear un aviso (interno; lo usan las dos entradas del cliente) ----------
create or replace function app.crear_aviso_pago(p_id_cliente integer, p_monto numeric, p_metodo text, p_ref text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_com integer; v_saldo numeric; v_pend numeric; v_ref text := nullif(upper(regexp_replace(coalesce(p_ref, ''), '[^A-Za-z0-9]', '', 'g')), ''); v_nom text; v_id bigint;
begin
  select id_comercio, nombre into v_com, v_nom from clientes where id_cliente = p_id_cliente;
  if v_com is null then return jsonb_build_object('ok', false, 'error', 'Cliente no válido'); end if;
  if p_metodo is null or p_metodo not in ('Bre-B', 'Nequi', 'Daviplata', 'Efectivo', 'Tarjeta') then return jsonb_build_object('ok', false, 'error', 'Elige cómo pagaste'); end if;
  if p_monto is null or p_monto <= 0 or p_monto > 100000000 then return jsonb_build_object('ok', false, 'error', 'Escribe el valor que pagaste'); end if;
  if v_ref is not null and char_length(v_ref) not between 3 and 40 then return jsonb_build_object('ok', false, 'error', 'La referencia debe tener entre 3 y 40 caracteres'); end if;
  select coalesce(sum(case when tipo = 'Cargo' then monto else -monto end), 0) into v_saldo from cartera_movimientos where id_cliente = p_id_cliente;
  if v_saldo <= 0 then return jsonb_build_object('ok', false, 'error', 'No tienes saldo pendiente'); end if;
  select coalesce(sum(monto), 0) into v_pend from pagos_avisados where id_cliente = p_id_cliente and estado = 'Pendiente';
  if p_monto + v_pend > v_saldo then return jsonb_build_object('ok', false, 'error', 'El valor supera tu saldo pendiente (contando los avisos que tu tienda aún está revisando)'); end if;
  if (select count(*) from pagos_avisados where id_cliente = p_id_cliente and estado = 'Pendiente') >= 3 then
    return jsonb_build_object('ok', false, 'error', 'Ya tienes 3 avisos en revisión. Espera a que tu tienda los confirme.'); end if;
  if (select count(*) from pagos_avisados where id_cliente = p_id_cliente and creado > now() - interval '1 day') >= 10 then
    return jsonb_build_object('ok', false, 'error', 'Hiciste muchos avisos hoy. Inténtalo mañana o habla con tu tienda.'); end if;
  if v_ref is not null and exists (select 1 from pagos_avisados where id_comercio = v_com and referencia = v_ref and estado <> 'Rechazado') then
    return jsonb_build_object('ok', false, 'error', 'Esa referencia ya fue registrada'); end if;
  insert into pagos_avisados (id_comercio, id_cliente, monto, metodo, referencia) values (v_com, p_id_cliente, p_monto, p_metodo, v_ref) returning id_aviso into v_id;
  return jsonb_build_object('ok', true);
end $$;
revoke all on function app.crear_aviso_pago(integer, numeric, text, text) from public, anon, authenticated;

create or replace function public.cuenta_avisar_pago_google(p_id_comercio integer, p_monto numeric, p_metodo text, p_referencia text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_uid uuid := auth.uid(); v_id integer;
begin
  if v_uid is null then raise exception 'Inicia sesión'; end if;
  select id_cliente into v_id from clientes_autoservicio where auth_user_id = v_uid and id_comercio = p_id_comercio and estado = 'Aprobado';
  if v_id is null then return jsonb_build_object('ok', false, 'error', 'No encontramos tu cuenta en esa tienda.'); end if;
  return app.crear_aviso_pago(v_id, p_monto, p_metodo, p_referencia);
end $$;

create or replace function public.cuenta_avisar_pago_enlace(p_token text, p_pin text, p_monto numeric, p_metodo text, p_referencia text)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_r jsonb; v_id integer;
begin
  v_r := public.cuenta_por_enlace(p_token, p_pin);
  if not (v_r->>'ok')::boolean then return v_r; end if;
  select id_cliente into v_id from cliente_accesos where tipo = 'enlace' and secreto_hash = extensions.digest(convert_to(btrim(p_token), 'utf8'), 'sha256');
  return app.crear_aviso_pago(v_id, p_monto, p_metodo, p_referencia);
end $$;

-- "Mi cuenta" muestra los últimos avisos y su estado
do $$ declare v_def text; v_new text; begin
  v_def := pg_get_functiondef('app.cuenta_cliente(integer)'::regprocedure);
  v_new := replace(v_def, '''como_pagar'', v_pago,',
    '''como_pagar'', v_pago, ''avisos'', coalesce((select jsonb_agg(jsonb_build_object(''monto'', a.monto, ''metodo'', a.metodo, ''estado'', a.estado, ''nota'', a.nota_tendero, ''fecha'', a.creado) order by a.creado desc) from (select * from pagos_avisados where id_cliente = p_id order by creado desc limit 5) a), ''[]''::jsonb),');
  if v_new = v_def then raise exception 'cuenta_cliente sin cambios'; end if;
  execute v_new;
end $$;

-- ---------- Tendero ----------
create or replace function public.pagos_avisados_listar()
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare v_com integer := app.mi_comercio();
begin
  if not app.tiene_permiso('fiados') then raise exception 'Tu rol no tiene permiso para esto' using errcode = '42501'; end if;
  return jsonb_build_object(
    'pendientes', coalesce((select jsonb_agg(x order by x->>'creado') from (select jsonb_build_object('id_aviso', a.id_aviso, 'id_cliente', a.id_cliente, 'cliente', c.nombre, 'telefono', c.telefono,
        'monto', a.monto, 'metodo', a.metodo, 'referencia', a.referencia, 'creado', a.creado,
        'saldo', (select coalesce(sum(case when m.tipo = 'Cargo' then m.monto else -m.monto end), 0) from cartera_movimientos m where m.id_cliente = a.id_cliente)) as x
        from pagos_avisados a join clientes c on c.id_cliente = a.id_cliente where a.id_comercio = v_com and a.estado = 'Pendiente') q), '[]'::jsonb),
    'recientes', coalesce((select jsonb_agg(x order by x->>'resuelto' desc) from (select jsonb_build_object('cliente', c.nombre, 'monto', a.monto, 'metodo', a.metodo, 'estado', a.estado, 'resuelto', a.resuelto, 'nota', a.nota_tendero) as x
        from pagos_avisados a join clientes c on c.id_cliente = a.id_cliente where a.id_comercio = v_com and a.estado <> 'Pendiente' order by a.resuelto desc limit 8) q), '[]'::jsonb));
end $$;

create or replace function public.pago_aviso_resolver(p_id_aviso bigint, p_confirmar boolean, p_monto numeric default null, p_nota text default null)
returns jsonb language plpgsql security definer set search_path = public as $$
declare v_com integer := app.mi_comercio(); a pagos_avisados%rowtype; v_ab jsonb; v_nota text := nullif(btrim(coalesce(p_nota, '')), ''); v_nom text;
begin
  if not app.tiene_permiso('fiados') then raise exception 'Tu rol no tiene permiso para esto' using errcode = '42501'; end if;
  select * into a from pagos_avisados where id_aviso = p_id_aviso and id_comercio = v_com for update;
  if not found then raise exception 'Aviso no encontrado'; end if;
  if a.estado <> 'Pendiente' then raise exception 'Este aviso ya fue resuelto'; end if;
  select nombre into v_nom from clientes where id_cliente = a.id_cliente;
  if p_confirmar then
    v_ab := public.registrar_abono(a.id_cliente, coalesce(p_monto, a.monto), a.metodo, 'Aviso del cliente' || coalesce(' · ref ' || a.referencia, ''));
    update pagos_avisados set estado = 'Confirmado', resuelto = now(), resuelto_por = app.mi_empleado(), id_movimiento = (v_ab->>'id_movimiento')::integer, nota_tendero = v_nota where id_aviso = a.id_aviso;
    perform app.equipo_log(v_com, app.mi_empleado(), null, 'pago_aviso', 'Confirmó el pago avisado de ' || v_nom);
    return v_ab;
  end if;
  if v_nota is null or char_length(v_nota) < 3 then raise exception 'Escribe el motivo para rechazarlo (el cliente lo verá)'; end if;
  if char_length(v_nota) > 160 then raise exception 'El motivo es muy largo (máximo 160 letras)'; end if;
  update pagos_avisados set estado = 'Rechazado', resuelto = now(), resuelto_por = app.mi_empleado(), nota_tendero = v_nota where id_aviso = a.id_aviso;
  perform app.equipo_log(v_com, app.mi_empleado(), null, 'pago_aviso', 'Rechazó el pago avisado de ' || v_nom);
  return jsonb_build_object('rechazado', true);
end $$;

